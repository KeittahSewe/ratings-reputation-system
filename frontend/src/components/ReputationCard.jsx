import { formatScore, formatStored, plural } from '../lib/format.js'
import { AiTag } from './Tag.jsx'
import { Card } from './Card.jsx'
import { EmptyState } from './EmptyState.jsx'
import { SentimentBar } from './SentimentBar.jsx'
import styles from './ReputationCard.module.css'

const TIMES = '\u00d7'
const FULL_HISTORY_JOBS = 10

// The reputation card of Figures 4.7 and 4.8, the screen's answer to literature
// gap 1: the score never appears without its three components, what each is
// built from, the sentiment distribution behind the sentiment part, and the
// formula worked through with this user's own stored numbers.
//
// reputation: the API's reputation object, or null before any review counts.
// own: true on the signed-in user's own profile ("your score").
export function ReputationCard({ reputation, completedJobs, role, own, showDistribution = true }) {
  if (!reputation) {
    return (
      <Card title="Reputation score" action={<AiTag>Generated by the scoring engine</AiTag>} ai>
        <EmptyState title="No score yet">
          A score appears once a first review has been classified and both parties can see it. Until then there is
          nothing to calculate from.
        </EmptyState>
      </Card>
    )
  }

  const r = reputation
  const reviews = plural(r.review_count, 'review')
  return (
    <Card title="Reputation score" action={<AiTag>Generated by the scoring engine</AiTag>} ai>
      <div className={styles.scoreRow}>
        <div className={styles.overall}>
          <span className={styles.overallValue}>{formatScore(r.score)}</span>
          <span className={styles.overallNote}>out of 5.0</span>
          {r.provisional && <span className={styles.provisional}>Provisional</span>}
        </div>
        <div className={styles.components}>
          <Component label="Rating component" value={r.ratings_component} note={`Mean of ${plural(r.review_count, 'star rating')}`} />
          <Component
            label="Sentiment component"
            value={r.sentiment_component}
            note="From DistilBERT classification of review text"
          />
          <Component label="Job history component" value={r.history_component} note={historyNote(completedJobs)} />
        </div>
      </div>

      {showDistribution && r.sentiment_counts && <SentimentBar counts={r.sentiment_counts} />}

      <div className={styles.how}>
        <p>
          <strong>How this is calculated:</strong> {own ? 'your' : 'this'} reputation score is 40 percent star ratings,
          40 percent review sentiment and 20 percent job history. Sentiment is classified from the text of each review
          by DistilBERT and counts positive as 5, neutral as 3 and negative as 1. Job history reaches full credit at{' '}
          {FULL_HISTORY_JOBS} completed jobs
          {role === 'client' ? ', and a job cancelled after a worker was assigned counts against it' : ''}. Only reviews
          both parties can see are counted, from {reviews} so far.
          {r.provisional &&
            ' While fewer than 3 reviews count, one neutral review is added to the sentiment part, so a single review cannot produce a perfect score.'}
        </p>
        <p className={styles.formula}>
          0.4 {TIMES} {formatStored(r.ratings_component)} + 0.4 {TIMES} {formatStored(r.sentiment_component)} + 0.2{' '}
          {TIMES} {formatStored(r.history_component)} = {formatStored(r.score)}, shown as {formatScore(r.score)}
        </p>
      </div>
    </Card>
  )
}

function Component({ label, value, note }) {
  return (
    <div className={styles.component}>
      <span className={styles.componentLabel}>{label}</span>
      <span className={styles.componentValue}>{formatScore(value)} / 5.0</span>
      <span className={styles.componentNote}>{note}</span>
    </div>
  )
}

function historyNote(completed) {
  if (completed === undefined || completed === null) return 'From completed jobs'
  const jobs = `${plural(completed, 'job')} completed`
  if (completed < FULL_HISTORY_JOBS) return `${jobs}, full credit at ${FULL_HISTORY_JOBS}`
  return jobs
}
